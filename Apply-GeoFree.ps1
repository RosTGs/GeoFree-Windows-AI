function Test-IsAdmin {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = [Security.Principal.WindowsPrincipal]::new($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-GeoFreeIP {
    $fallbackIP = "80.74.24.165"

    try {
        $output = & cmd.exe /d /c "nslookup chatgpt.com dns.comss.one 2>&1"
        $ips = foreach ($line in $output) {
            if ($line -match "Address(?:es)?:\s+(\d{1,3}(?:\.\d{1,3}){3})") {
                $matches[1]
            }
        }

        $resolved = $ips | Where-Object { $_ -notmatch "^(195\.133\.25\.16|212\.109\.195\.93)$" } | Select-Object -Last 1
        if ($resolved) {
            return $resolved
        }
    }
    catch {
        Write-Warning "Could not resolve GeoFree IP via dns.comss.one: $($_.Exception.Message)"
    }

    Write-Warning "Using fallback GeoFree IP: $fallbackIP"
    return $fallbackIP
}

if (-not (Test-IsAdmin)) {
    if ($NoElevate) {
        throw "Administrator rights are required to edit the Windows hosts file."
    }

    $arguments = @(
        "-NoProfile",
        "-ExecutionPolicy", "Bypass",
        "-File", "`"$PSCommandPath`""
    )

    if ($IP) {
        $arguments += @("-IP", $IP)
    }

    $process = Start-Process -FilePath "powershell.exe" -Verb RunAs -ArgumentList $arguments -Wait -PassThru
    exit $process.ExitCode
}

try {
    Write-GeoFreeLog "Started. Admin=$(Test-IsAdmin). IP argument=$IP"

    if (-not $IP) {
        $IP = Get-GeoFreeIP
    }

    if ($IP -notmatch "^\d{1,3}(?:\.\d{1,3}){3}$") {
        throw "Invalid IPv4 address: $IP"
    }

    $hostsPath = Join-Path $env:SystemRoot "System32\drivers\etc\hosts"
    $timestamp = Get-Date -Format "yyyyMMdd_HHmmss"
    $backupPath = "$hostsPath.backup.$timestamp"
    $startMarker = "# --- GEOFREE START ---"
    $endMarker = "# --- GEOFREE END ---"
    $startPattern = [regex]::Escape($startMarker)
    $endPattern = [regex]::Escape($endMarker)

    Write-GeoFreeLog "Backing up $hostsPath to $backupPath"
    Copy-Item -LiteralPath $hostsPath -Destination $backupPath -Force

    $existing = [IO.File]::ReadAllText($hostsPath)
    $withoutOldBlock = [regex]::Replace(
        $existing,
        "(?ms)^\s*$startPattern.*?^\s*$endPattern\r?\n?",
        ""
    )

    $domainPattern = ($Domains | ForEach-Object { [regex]::Escape($_) }) -join "|"
    $keptLines = foreach ($line in ($withoutOldBlock -split "\r?\n")) {
        if ($line -match "^\s*#") {
            $line
        }
        elseif ($line -match "(?i)(^|\s)($domainPattern)(\s|$)") {
            continue
        }
        else {
            $line
        }
    }

    $block = @(
        "",
        $startMarker,
        "# Generated by Apply-GeoFree.ps1 on $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")",
        "# Backup: $backupPath"
    ) + ($Domains | ForEach-Object { "$IP $_" }) + @($endMarker)

    $newLine = [Environment]::NewLine
    $newContent = (($keptLines + $block) -join $newLine).TrimEnd() + $newLine
    Write-GeoFreeLog "Writing hosts file. Length=$($newContent.Length)"
    [IO.File]::WriteAllText($hostsPath, $newContent, [Text.Encoding]::ASCII)

    ipconfig /flushdns | Out-Null
    Write-GeoFreeLog "Completed successfully."

    Write-Host "GeoFree hosts entries applied." -ForegroundColor Green
    Write-Host "IP: $IP"
    Write-Host "Backup: $backupPath"
    Write-Host "Restart browsers/apps that use these services."
}
catch {
    Write-GeoFreeLog "FAILED: $($_.Exception.Message)"
    throw
}
