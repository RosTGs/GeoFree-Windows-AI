#!/usr/bin/env bash
set -euo pipefail

IP="${1:-}"
HOSTS_FILE="/etc/hosts"
START_MARKER="# --- GEOFREE START ---"
END_MARKER="# --- GEOFREE END ---"

DOMAINS=(
  chatgpt.com
  ab.chatgpt.com
  www.chatgpt.com
  webrtc.chatgpt.com
  tcr9i.chat.openai.com
  operator.chatgpt.com
  sora.chatgpt.com
  auth.openai.com
  auth0.openai.com
  platform.openai.com
  platform.api.openai.com
  api.openai.com
  beta.api.openai.com
  cdn.oaistatic.com
  files.oaiusercontent.com
  cdn.auth0.com
  gemini.google.com
  aistudio.google.com
  labs.google.com
  generativelanguage.googleapis.com
  aisandbox-pa.googleapis.com
  alkalimakersuite-pa.clients6.google.com
  aitestkitchen.withgoogle.com
  copilot.microsoft.com
  sydney.bing.com
  edgeservices.bing.com
  claude.ai
  api.claude.ai
  platform.claude.ai
  www.claude.ai
  anthropic.com
  api.anthropic.com
  x.ai
  grok.com
  www.grok.com
  assets.grok.com
  accounts.x.ai
  elevenlabs.io
  api.elevenlabs.io
  www.elevenlabs.io
)

log() {
  printf '%s\n' "$*"
}

die() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

is_valid_ipv4() {
  local ip="$1" part
  [[ "$ip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1
  IFS='.' read -r -a parts <<< "$ip"
  for part in "${parts[@]}"; do
    (( 10#$part >= 0 && 10#$part <= 255 )) || return 1
  done
}

require_root() {
  if [[ "$(id -u)" -ne 0 ]]; then
    die "Run with sudo: sudo $0 <ip>"
  fi
}

flush_dns() {
  dscacheutil -flushcache 2>/dev/null || true
  killall -HUP mDNSResponder 2>/dev/null || true
}

require_root
[[ -n "$IP" ]] || die "Missing IP. Example: sudo ./apply-hosts.sh 80.74.24.165"
is_valid_ipv4 "$IP" || die "Invalid IPv4 address: $IP"
[[ -f "$HOSTS_FILE" ]] || die "Missing hosts file: $HOSTS_FILE"

STAMP="$(date +%Y%m%d_%H%M%S)"
BACKUP_FILE="${HOSTS_FILE}.backup.${STAMP}"
TMP_FILE="$(mktemp)"
trap 'rm -f "$TMP_FILE" "$TMP_FILE.without_block"' EXIT

cp -p "$HOSTS_FILE" "$BACKUP_FILE"

awk -v start="$START_MARKER" -v end="$END_MARKER" '
  $0 == start { skip = 1; next }
  $0 == end { skip = 0; next }
  !skip { print }
' "$HOSTS_FILE" > "$TMP_FILE.without_block"

awk -v domains="${DOMAINS[*]}" '
  BEGIN {
    n = split(domains, d, " ")
    for (i = 1; i <= n; i++) target[d[i]] = 1
  }
  /^[[:space:]]*#/ { print; next }
  {
    found = 0
    for (i = 2; i <= NF; i++) {
      if ($i in target) { found = 1; break }
    }
    if (!found) print
  }
' "$TMP_FILE.without_block" > "$TMP_FILE"

{
  printf '\n%s\n' "$START_MARKER"
  printf '# Generated by apply-hosts.sh on %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"
  printf '# Backup: %s\n' "$BACKUP_FILE"
  for domain in "${DOMAINS[@]}"; do
    printf '%s %s\n' "$IP" "$domain"
  done
  printf '%s\n' "$END_MARKER"
} >> "$TMP_FILE"

cat "$TMP_FILE" > "$HOSTS_FILE"
flush_dns

log "Applied GeoFree hosts entries."
log "IP: $IP"
log "Backup: $BACKUP_FILE"
